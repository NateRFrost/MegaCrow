import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));
const docsDir = path.resolve(scriptsDir, "..");
const megaloSrc = path.resolve(docsDir, "../megalo/src");
const entry = path.join(docsDir, ".vitepress/megalo-code-html.ts");
const outfile = path.join(docsDir, ".vitepress/megalo-highlight.bundle.mjs");

/** Resolve megalo package `src/...` path aliases used throughout the compiler. */
const megaloSrcAliasPlugin = {
  name: "megalo-src-alias",
  setup(build) {
    build.onResolve({ filter: /^src(\/|$)/ }, (args) => {
      const rest = args.path === "src" ? "index.ts" : args.path.slice("src/".length);
      const candidates = [
        path.join(megaloSrc, rest),
        path.join(megaloSrc, `${rest}.ts`),
        path.join(megaloSrc, rest, "index.ts"),
      ];
      for (const candidate of candidates) {
        if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) {
          return { path: candidate };
        }
      }
      return {
        path: path.join(megaloSrc, `${rest}.ts`),
      };
    });
  },
};

await esbuild.build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  logLevel: "info",
  banner: {
    js: "// Generated by scripts/bundle-docs-highlight.mjs — do not edit.\n",
  },
  plugins: [megaloSrcAliasPlugin],
  external: ["monaco-editor"],
  loader: {
    ".json": "json",
  },
});

console.log(`Wrote ${path.relative(docsDir, outfile)}`);
